function numeric05() {
  const m = "05";
  const refs = REF_CARTO;
  const out: object[] = [];
  // 比例尺：图上 1cm 实地多少 m
  const scales: [number, number][] = [[2000, 1], [5000, 1], [10000, 1], [25000, 1], [50000, 2], [100000, 2], [250000, 2], [500000, 3], [1000000, 3], [2000000, 3]];
  for (const [scale, d] of scales) {
    out.push(numeric(m, d, "1:" + scale.toLocaleString("en-US") + " 地形图上 1 cm 对应实地多少米？", scale / 100, scale * 0.001, "1 cm × " + scale + " = " + scale + " cm = " + (scale / 100).toLocaleString("en-US") + " m。", refs, { unit: "m" }));
  }
  // 实地 → 图上
  const toMap: [number, number, number, number][] = [
    [10, 50000, 20, 2], [5, 25000, 20, 2], [120, 1000000, 12, 2], [3, 100000, 30, 3], [80, 4000000, 2, 3], [25, 500000, 5, 3],
  ];
  for (const [km, scale, ans, d] of toMap) {
    out.push(numeric(m, d, "实地 " + km + " km 的线段画在 1:" + scale.toLocaleString("en-US") + " 图上约多少厘米？（保留 1 位小数）", ans, ans * 0.05, km + " km = " + (km * 100000).toLocaleString("en-US") + " cm ÷ " + scale.toLocaleString("en-US") + " = " + ans + " cm。", refs, { unit: "cm" }));
  }
  // 分级计算
  out.push(numeric(m, 2, "某县 GDP 最小 2.0、最大 22.0（亿元），等间距分 5 档，组距是多少？", 4, 0.05, "(22 − 2) / 5 = 4 亿元/档。", refs));
  out.push(numeric(m, 2, "某县 GDP 最小 8.5、最大 63.5，等间距分 5 档，组距是多少？", 11, 0.05, "(63.5 − 8.5) / 5 = 11。", refs));
  out.push(numeric(m, 3, "某指标最小 12.4、最大 92.4，等间距分 4 档，第 2 档的上边界是多少？", 52.4, 0.05, "组距 = (92.4 − 12.4)/4 = 20；第 1 档上界 32.4，第 2 档上界 = 12.4 + 2×20 = 52.4。", refs));
  out.push(numeric(m, 1, "40 个县按分位数法分 4 档，每档几个县？", 10, 0, "40 / 4 = 10 个县/档。", refs));
  out.push(numeric(m, 1, "120 个乡镇按分位数法分 6 档，每档几个乡镇？", 20, 0, "120 / 6 = 20。", refs));
  out.push(numeric(m, 2, "18 个街道按分位数法分 6 档，每档几个街道？", 3, 0, "18 / 6 = 3。", refs));
  return out;
}


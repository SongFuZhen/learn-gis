export function gen01(count: number) {
  const out: object[] = [];
  out.push(...tfBatch("01", TF, [REF.gisWiki, REF.topology]));
  SINGLES.forEach((s) => out.push(single("01", 2, s.stem, s.opts, s.ans, s.exp, s.refs)));
  SHORTS.forEach((s, i) =>
    out.push(short("01", i % 3 === 0 ? 1 : 2, s.stem, s.accepted, s.exp, [REF.gisWiki], s.ph)),
  );
  MULTIS.forEach((m) => out.push(multi("01", 3, m.stem, m.opts, m.ans, m.exp, [REF.gisWiki])));
  return out.slice(0, count);
}

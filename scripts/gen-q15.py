def pick_refs(q):
    text = q["stem"] + q["explanation"]
    refs = []
    if any(k in text for k in ["TLE", "SGP4", "NORAD", "CelesTrak", "两行根数"]):
        refs.append(REF_CELESTRAK)
    if any(k in text for k in ["ISS", "国际空间站", "空间站"]):
        refs.append(REF_NASA)
    if any(k in text for k in ["Landsat", "Sentinel", "遥感", "太阳同步"]):
        refs.append(REF_USGS)
    if any(k in text for k in ["ESA", "欧洲"]):
        refs.append(REF_ESA)
    if not refs:
        refs.append(REF_NASA)
    return refs

def add(q):
    global i
    i += 1
    q["id"] = f"gis-{q["module"]}-{i:03d}"
    if not q["refs"]:
        q["refs"] = pick_refs(q)
    questions.append(q)

